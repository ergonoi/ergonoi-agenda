#!/usr/bin/env python3
"""Writes the word lists into clients/core/agenda-core.js and clients/cli/journal/wordlists.go.

Usage: python3 clients/core/wordlists/build.py
"""
import pathlib
import re

here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
LANGS = [("en", "English"), ("de", "Deutsch"), ("fr", "Français"), ("es", "Español"), ("it", "Italiano"), ("pt", "Português"), ("cs", "Čeština")]
lists = {}
for code, _ in LANGS:
    words = (here / f"{code}.txt").read_text(encoding="ascii").split()
    if len(words) != 2048 or len(set(words)) != 2048:
        raise SystemExit(f"{code}.txt must hold 2048 distinct words")
    lists[code] = words

js = "// @@wordlists-begin@@ generated by clients/core/wordlists/build.py; do not edit by hand.\n"
js += "// Word lists of 2048 words each (architecture 8.2): the first is English (BIP39).\n"
js += "const WORDLISTS = {\n"
for code, name in LANGS:
    js += f'  {code}: {{ name: "{name}", words: "{" ".join(lists[code])}".split(" ") }},\n'
js += "};\n// @@wordlists-end@@"
core = root / "clients/core/agenda-core.js"
s = core.read_text(encoding="utf-8")
pat = re.compile(r"// @@wordlists-begin@@.*?// @@wordlists-end@@", re.S)
if len(pat.findall(s)) != 1:
    raise SystemExit("agenda-core.js must contain the wordlists markers exactly once")
core.write_text(pat.sub(lambda _: js, s), encoding="utf-8")

go = "// Code generated by clients/core/wordlists/build.py; DO NOT EDIT.\n\npackage journal\n\n"
go += "// wordlists holds the lists of 2048 words for phrases and ally codes (architecture 8.2).\nvar wordlists = map[string][]string{\n"
for code, _ in LANGS:
    go += f'\t"{code}": {{\n'
    w = lists[code]
    for i in range(0, 2048, 8):
        go += "\t\t" + ", ".join(f'"{x}"' for x in w[i:i + 8]) + ",\n"
    go += "\t},\n"
go += "}\n\n// wordlistOrder is the order in which lists are tried when words fit several.\nvar wordlistOrder = []string{" + ", ".join(f'"{c}"' for c, _ in LANGS) + "}\n"
(root / "clients/cli/journal/wordlists.go").write_text(go, encoding="utf-8")
print("ok")
